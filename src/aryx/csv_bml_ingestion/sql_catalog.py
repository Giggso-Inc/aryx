"""Step 3 (runtime side) — locate and read the LLM-authored schema/index files.

The .sql files themselves are authored by LLM agents (never generated by
code) and committed under ``sql/<table>/``; this module only finds and
splits them. Splitting rule (documented in the files' headers): a statement
ends at a line whose last non-space character is ``;``; ``--`` comment lines
are dropped; no PL/SQL blocks.
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from aryx.csv_bml_ingestion.constants import BML_SOURCE_FILE, INDEXES_FILE, SCHEMA_FILE, SQL_ROOT
from aryx.csv_bml_ingestion.errors import SqlArtifactsMissingError


@dataclass(frozen=True, slots=True)
class SqlArtifacts:
    """The schema and index statements for one table, plus where they came from."""

    table: str
    directory: Path
    schema_statements: tuple[str, ...]
    index_statements: tuple[str, ...]


def split_statements(text: str) -> tuple[str, ...]:
    """Split ``text`` into statements (see module docstring for the rule)."""
    statements: list[str] = []
    buf: list[str] = []
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("--"):
            continue
        buf.append(line)
        if line.endswith(";"):
            statements.append(" ".join(buf).rstrip(";").strip())
            buf = []
    if buf:
        statements.append(" ".join(buf).strip())
    return tuple(statements)


def sql_dir(table: str, root: Path = SQL_ROOT) -> Path:
    """Directory holding ``table``'s reference SQL files."""
    return root / table.lower()


def load_sql_artifacts(table: str, root: Path = SQL_ROOT) -> SqlArtifacts:
    """Read ``schema.sql`` and ``indexes.sql`` for ``table``.

    Raises:
        SqlArtifactsMissingError: the directory or either file is absent, or
            the schema file defines no statement.
    """
    directory = sql_dir(table, root)
    schema_path, index_path = directory / SCHEMA_FILE, directory / INDEXES_FILE
    missing = [p.name for p in (schema_path, index_path) if not p.is_file()]
    if missing:
        raise SqlArtifactsMissingError(
            f"table {table!r}: missing {', '.join(missing)} in {directory} — a BML query exists "
            f"for it, so generate the schema/index files (LLM agent step) before ingesting"
        )
    schema = split_statements(schema_path.read_text(encoding="utf-8"))
    if not schema:
        raise SqlArtifactsMissingError(f"table {table!r}: {schema_path} contains no SQL statement")
    return SqlArtifacts(
        table=table, directory=directory, schema_statements=schema,
        index_statements=split_statements(index_path.read_text(encoding="utf-8")),
    )


def bml_source_doc(table: str, root: Path = SQL_ROOT) -> Path:
    """Path of the human-readable BML evidence file for ``table`` (may not exist)."""
    return sql_dir(table, root) / BML_SOURCE_FILE
