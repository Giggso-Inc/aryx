"""Entity ID allocation helpers shared by EntityStore's Oracle write paths.

Split out of `store/entity_store.py` (Raven Style Compliance Plan, Phase 2a,
2026-09-03).
"""
from __future__ import annotations

import json
import logging
import re
from typing import Any

from aryx.queries import load

logger = logging.getLogger(__name__)

_entity_seq_cache: dict[str, str] = {}  # table_name → identity sequence name


def _fetch_entity_ids(cur: Any, n: int) -> list[int]:
    """Fetch n identity sequence values from aryx_entity in one round-trip.

    Queries user_tab_identity_cols once to discover the sequence name, then
    uses CONNECT BY LEVEL to pull n NEXTVALs in a single SELECT.
    """
    if "ARYX_ENTITY" not in _entity_seq_cache:
        cur.execute(load("select_entity_seq_name"))
        row = cur.fetchone()
        if row:
            _entity_seq_cache["ARYX_ENTITY"] = row[0]
            logger.info("entity identity sequence resolved name=%s", row[0])
        else:
            raise RuntimeError(
                "user_tab_identity_cols returned no row for ARYX_ENTITY — "
                "run migration 0032_entity_by_default_identity.sql"
            )
    seq_name = _entity_seq_cache["ARYX_ENTITY"]
    if not re.fullmatch(r"[A-Z][A-Z0-9_$#]*", seq_name):
        raise RuntimeError("invalid ARYX_ENTITY identity sequence name")
    cur.execute(
        load("select_next_oracle_entity_ids").format(sequence=seq_name),
        (n,),
    )
    ids = [int(r[0]) for r in cur.fetchall()]
    if len(ids) != n:
        raise RuntimeError(
            f"identity sequence returned {len(ids)} IDs for {n} requested — "
            "check migration 0032 ran (GENERATED BY DEFAULT AS IDENTITY)"
        )
    return ids


def _dumps(value: object) -> str:
    """JSON-encode, stringifying non-native types."""
    return json.dumps(value, default=str)
