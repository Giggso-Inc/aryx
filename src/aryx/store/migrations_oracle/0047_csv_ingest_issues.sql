-- csv_bml_ingestion: keep CSV rows / files that were NOT loaded, so the UI can show them and re-run.
-- Oracle ADB version. Runs that loaded cleanly are not stored; a run is stored when it was skipped or
-- failed, or loaded with rejected rows.
--
-- aryx_csv_ingest_run      one row per stored CSV ingestion (counts, status, reason).
--                          file_gz_b64 holds the original file (gzip + base64 text, the same plain-text
--                          codec idea as discovery_store_codec) ONLY for skipped/failed runs, so a
--                          file-level re-run needs no re-upload. NULL when over the size cap.
-- aryx_csv_ingest_reject   one row per rejected CSV row (capped per run): source line, reason, and the
--                          row as JSON ({"cells": [...]} malformed, {"columns": {...}} over-length).
-- No FK to aryx_workspace (matches the graph tables); rows are always filtered by workspace_id.

BEGIN
  EXECUTE IMMEDIATE 'CREATE TABLE aryx_csv_ingest_run (
    run_id           VARCHAR2(32)              NOT NULL,
    workspace_id     NUMBER(10)                NOT NULL,
    job_id           VARCHAR2(64),
    source_file      VARCHAR2(256)             NOT NULL,
    table_name       VARCHAR2(128),
    status           VARCHAR2(16)              NOT NULL,
    error_code       VARCHAR2(40),
    message          VARCHAR2(1000),
    rows_loaded      NUMBER(12)   DEFAULT 0    NOT NULL,
    rows_bad         NUMBER(12)   DEFAULT 0    NOT NULL,
    rows_rejected    NUMBER(12)   DEFAULT 0    NOT NULL,
    rows_truncated   NUMBER(12)   DEFAULT 0    NOT NULL,
    reject_total     NUMBER(12)   DEFAULT 0    NOT NULL,
    reject_stored    NUMBER(12)   DEFAULT 0    NOT NULL,
    file_size        NUMBER(12),
    file_gz_b64      CLOB,
    rerun_of         VARCHAR2(32),
    state            VARCHAR2(16) DEFAULT ''open'' NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_aryx_csv_ingest_run PRIMARY KEY (run_id)
  )';
-- ORA-00955: table already exists (re-running this migration). Anything else must re-raise.
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX idx_csv_ingest_run_ws ON aryx_csv_ingest_run (workspace_id, created_at)';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 AND SQLCODE != -1408 THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX idx_csv_ingest_run_job ON aryx_csv_ingest_run (job_id)';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 AND SQLCODE != -1408 THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE TABLE aryx_csv_ingest_reject (
    reject_id        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    run_id           VARCHAR2(32)              NOT NULL,
    workspace_id     NUMBER(10)                NOT NULL,
    line_no          NUMBER(12),
    reason_code      VARCHAR2(40)              NOT NULL,
    reason           VARCHAR2(1000),
    row_json         CLOB,
    state            VARCHAR2(16) DEFAULT ''open'' NOT NULL,
    attempts         NUMBER(5)    DEFAULT 0    NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    resolved_at      TIMESTAMP WITH TIME ZONE,
    CONSTRAINT pk_aryx_csv_ingest_reject PRIMARY KEY (reject_id),
    CONSTRAINT fk_csv_reject_run FOREIGN KEY (run_id)
      REFERENCES aryx_csv_ingest_run (run_id) ON DELETE CASCADE
  )';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX idx_csv_reject_run_state ON aryx_csv_ingest_reject (run_id, state)';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 AND SQLCODE != -1408 THEN RAISE; END IF;
END;
/
