"""
Metadata-dict builder for local/app storage_type datasources (the fallback
branch of the original generate_datasource_metadata: everything that is
neither "database" nor a recognized "cloud" provider).

Private module: called only by _metadata_generator.generate_datasource_metadata.
Split out verbatim from the original monolithic function so each storage-type
branch can live in its own file; the dict contents/keys are unchanged.
"""

from typing import Any, Dict, Optional


def build_local_app_metadata(
    *,
    filename: str,
    storage_type: str,
    channel_id: str,
    workspace_id: str,
    user_id: str,
    file_size: int,
    provider: Optional[str],
    app_type: Optional[str],
    log_type: Optional[str],
    config: Optional[Dict[str, Any]],
    is_embedding_required: bool,
    file_format: str,
    unique_filename: str,
    giggs_token: str,
) -> Dict[str, Any]:
    """Build the raw (uncleaned) metadata dict for a local/app-storage datasource."""
    metadata = {
        "accessKey": "",
        "accessKeyId": None,
        "accessToken": "",
        "accountId": "",
        "app": [],
        "appType": app_type,
        "logType": log_type,
        "attachments": None,
        "azureKey": None,
        "botFlag": 1,
        "byodToken": None,
        "clientId": None,
        "clientSecret": None,
        "contextFileGiggsoVaultIds": None,
        "contextFiles": None,
        "cookies": [],
        "countFlg": 0,
        "credentials": config or {},
        "databaseName": "",
        "databaseType": storage_type,
        "logFile": True,
        "datasourcePrivacy": 0,
        "dataType": "referenceData",
        "disconnectDataSource": 0,
        "emailAttachmentFlg": 0,
        "emailValidate": 0,
        "embeddingsGenerated": 0,
        "embeddingStatus": 1 if is_embedding_required else 0,
        "emrClusterId": None,
        "enableDecrypt": 0,
        "endpoint": None,
        "errorCode": None,
        "errorMessage": None,
        "externalAppId": None,
        "fileDetails": None,
        "fileFormat": file_format,
        "fileNameAndPath": [],
        "fileOwnerId": None,
        "giggsoToken": giggs_token,
        "giggsoTokens": [],
        "googleDriveFiles": [],
        "workspaceChannelFlg": 1,
        "hostname": None,
        "indexColumnName": None,
        "indexColumnType": None,
        "isSummary": None,
        "isValidate": 1,
        "level": None,
        "localFileInfos": None,
        "localFiles": [unique_filename],
        "location": "",
        "maxCount": 10,
        "minCount": 0,
        "monitoringId": None,
        "multiSelect": 0,
        "objectName": None,
        "objectNames": None,
        "password": "",
        "port": None,
        "recordProcessType": None,
        "regenerateEmbeddings": 0,
        "regionName": None,
        "userId": user_id,
        "restrictedURLs": None,
        "scheduleEmbeddingDelay": None,
        "scheduleEmbeddingDelayTime": 0,
        "scheduleEmbeddingFlg": 0,
        "scheduleEmbeddingTimeUnit": None,
        "schemaName": "",
        "secretAccessKey": None,
        "secretKey": None,
        "serviceName": None,
        "siteName": None,
        "size": file_size,
        "startFrom": 0,
        "storageProvider": provider or "",
        "storageType": storage_type,
        "tableId": "",
        "tableName": "",
        "tableNames": None,
        "threadId": 0,
        "topicLevelFlg": 1,
        "update": None,
        "url": None,
        "useCaseType": None,
        "username": "",
        "validatedId": None,
        "warehouse": "",
        "workspaceId": workspace_id,
        "channelId": channel_id,
        "filename": filename,
        "unique_filename": unique_filename
    }
    return metadata
